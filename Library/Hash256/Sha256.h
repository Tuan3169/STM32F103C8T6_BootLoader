#ifndef _Sha256_H
#define _Sha256_H


//################################################# INCLUDE HEARDER #############################################
#include <stdint.h>
#include <stddef.h>

//#################################################     DEFINE    ###############################################


//#################################################     TYPEDEF   ###############################################
typedef struct {
    uint32_t state[8];
    uint64_t bitlen;
    uint8_t data[64];
    uint32_t datalen;
} Sha256Ctx;

//#################################################     VARIABLE  ###############################################


//#################################################     FUNCTION  ###############################################
void sha256_init(Sha256Ctx *ctx);
void sha256_update(Sha256Ctx *ctx, const uint8_t *data, size_t len);
void sha256_final(Sha256Ctx *ctx, uint8_t hash[32]);

#endif /* _Sha256_H */